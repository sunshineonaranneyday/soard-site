/**
 * The build's own content rules (src/content.config.ts), bundled for the server, so the SOARD connection for Claude
 * checks a page change exactly as the build will before saving it: a change the build would refuse (a Press story
 * with a category that isn't one of five, an event with no date) is never saved, so it can never stop a Publish.
 *
 * content.config.ts imports `astro:content` only for `defineCollection` (here a pass-through) and `astro/loaders`
 * only for `glob` (here nothing: the server reads no files). `astro/zod` is bundled as it is, so the server checks
 * with the very Zod the build uses. The output is committed (functions/api/_mcp/content-schema.gen.js) and
 * tests/mcp.test.mjs rebuilds it to prove it still matches content.config.ts: after changing content.config.ts,
 * run `node scripts/mcp-content-schema.mjs`.
 */

import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(ROOT, 'functions/api/_mcp/content-schema.gen.js');

const SHIMS = {
  'astro:content': 'export const defineCollection = (c) => c;\n',
  'astro/loaders': 'export const glob = () => null;\n',
  'zod-locales': 'export {};\n',
};
const HEADER = '// Generated by scripts/mcp-content-schema.mjs from src/content.config.ts: never edit by hand.\n';

/** The bundle's text */
export async function contentSchemaSource() {
  const r = await build({
    entryPoints: [join(ROOT, 'src/content.config.ts')],
    bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', minify: true, legalComments: 'none', write: false, logLevel: 'silent',
    mainFields: ['module', 'main'], absWorkingDir: ROOT,
    plugins: [{
      name: 'astro-content',
      setup(b) {
        b.onResolve({ filter: /^astro(:content|\/loaders)$/ }, (args) => ({ path: args.path, namespace: 'shim' }));
        // Zod 4's z carries its messages in every language (z.locales), 250 KB the server never uses: English, which
        // Zod sets itself (classic/schemas.js imports locales/en.js on its own), is all the build and the server speak
        b.onResolve({ filter: /locales[\\/]index\.js$/ }, (args) => (/[\\/]zod[\\/]/.test(args.importer) ? { path: 'zod-locales', namespace: 'shim' } : undefined));
        b.onLoad({ filter: /.*/, namespace: 'shim' }, (args) => ({ contents: SHIMS[args.path], resolveDir: ROOT, loader: 'js' }));
      },
    }],
  });
  return HEADER + r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await contentSchemaSource();
  await writeFile(OUT, text);
  console.log(`[mcp-content-schema] ${OUT.slice(ROOT.length + 1)}: ${Math.round(text.length / 1024)} KB`);
}
